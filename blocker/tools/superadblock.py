"""Maintain the strict tracker-host sections of the bundled Astra list.

Two public benchmarks probe hosts with `fetch(no-cors)` instead of loading a
script or an image, and community lists often match those hosts only for one
resource type (`$script`, `$image`, ...). A fetch-based probe -- and a real
`fetch`/XHR beacon -- therefore slips through even while the script is blocked.
Each reviewed inventory under `blocker/lists/` records one benchmark's
targets; this tool writes one host-anchored, type-agnostic `$important` rule
per host into `blocker/lists/astra-telemetry.txt`, between that inventory's
two marker lines:

  * `superadblock-hosts.json` -- Super Adblock Test (superadblocktest.com).
    The name of this file is historical; it now owns every strict section.
  * `adblocktester-hosts.json` -- Adblock Tester (adblocktester.pages.dev).
    Its local-script and cosmetic baits are covered by the hand-maintained
    heuristic rules above the generated sections, not by host rules.

A rule is not emitted when an earlier section or the hand-maintained head
already covers the host (itself or a parent domain), so the file never carries
two rules for one host.

Every host in an inventory is a real ad, tracker, attribution, analytics,
consent, affiliate, video-ad or device-maker telemetry endpoint. Two hosts are
deliberately not emitted as a bare host rule:

  * vk.com - the inventory only probes `/rtrg`; a host rule would block the
    whole social network. The existing path rule `||vk.com/rtrg?` stays.

Usage:
  python3 blocker/tools/superadblock.py --write   # refresh the sections
  python3 blocker/tools/superadblock.py --check   # fail on drift (CI)
"""
