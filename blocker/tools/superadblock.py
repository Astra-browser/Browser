"""Maintain the strict tracker-host section of the bundled Astra list.

`blocker/lists/superadblock-hosts.json` is the reviewed inventory of hosts
that the public Super Adblock Test (https://superadblocktest.com/) probes with
`fetch(no-cors)`. Community lists often match those hosts only for one
resource type (`$script`, `$image`, ...), so a fetch-based probe (and a real
`fetch`/XHR beacon) can slip through. This tool writes one host-anchored,
type-agnostic `$important` rule per host into
`blocker/lists/astra-telemetry.txt`, between the two marker lines.

Every host in the inventory is a real ad, tracker, attribution, analytics,
consent, affiliate, video-ad or device-maker telemetry endpoint. Two hosts are
deliberately not emitted as a bare host rule:

  * vk.com - the inventory only probes `/rtrg`; a host rule would block the
    whole social network. The existing path rule `||vk.com/rtrg?` stays.

Usage:
  python3 blocker/tools/superadblock.py --write   # refresh the section
  python3 blocker/tools/superadblock.py --check   # fail on drift (CI)
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
INVENTORY = os.path.join(ROOT, "blocker", "lists", "superadblock-hosts.json")
LIST = os.path.join(ROOT, "blocker", "lists", "astra-telemetry.txt")
START = "! >>> superadblock-strict (generated by blocker/tools/superadblock.py)"
END = "! <<< superadblock-strict"

# A host rule here must not capture a whole service. Add to this set with a
# comment when the inventory gains a path-scoped or shared-domain target.
SKIP = {
    "vk.com": "inventory probes only /rtrg; a host rule would block vk.com",
}

CATEGORY_ORDER = [
    "Ads",
    "Analytics",
    "Tracking & Fingerprinting",
    "Social Trackers",
    "Email Tracking & Live Chat",
    "Video Ads",
    "Affiliate Networks",
    "Consent Management",
    "A/B Testing",
    "OEM Vendors",
    "Advanced / Risky Host Checks",
    "Error Trackers",
]

CATEGORY_TITLE = {
    "Ads": "Advertising and mobile ad networks",
    "Analytics": "Analytics and product telemetry",
    "Tracking & Fingerprinting": "Cross-site tracking, attribution and fingerprinting",
    "Social Trackers": "Social platform pixels and SDKs (per-site shields restore embeds)",
    "Email Tracking & Live Chat": "Email, lifecycle messaging and live chat",
    "Video Ads": "Video ad delivery and monetisation",
    "Affiliate Networks": "Affiliate networks and link redirectors",
    "Consent Management": "Consent-management platforms (per-site shields restore a site's banner)",
    "A/B Testing": "Experimentation and feature-flag SDKs",
    "OEM Vendors": "Device-maker and connected-TV telemetry and advertising",
    "Advanced / Risky Host Checks": "Malvertising, pop-under and cryptomining hosts",
    "Error Trackers": "Error-reporting and session-replay endpoints",
}


def load():
    with open(INVENTORY, encoding="utf-8") as f:
        return json.load(f)


def render_section(data=None, head_text=""):
    data = data or load()
    # The hand-maintained sections already carry some of these hosts; a second
    # identical rule would trip the telemetry contract's one-rule invariant.
    existing = {
        line.strip()
        for line in head_text.splitlines()
        if line.strip() and not line.strip().startswith("!")
    }
    by_category = {}
    for entry in data["hosts"]:
        host = entry["host"].lower()
        if host in SKIP:
            continue
        rule = f"||{host}^$important"
        if rule in existing:
            continue
        category = entry["categories"][0]
        by_category.setdefault(category, []).append(host)

    lines = [
        START,
        "! Regenerate with: python3 blocker/tools/superadblock.py --write",
        "! Source inventory: blocker/lists/superadblock-hosts.json",
        f"! Captured: {data['captured']} from {data['source']}",
        "!",
        "! The public test fetches these hosts with fetch(no-cors), and real",
        "! beacons use the same shape. Community rules that only match a",
        "! script/image subresource do not stop a fetch, so every entry here is",
        "! host-anchored and $important: it covers every request type. A person",
        "! who needs a social embed, consent banner, chat widget or affiliate",
        "! redirect can pause shields for that one site from the address panel",
        "! or the sidebar shield.",
        END,
    ]
    if SKIP:
        lines.append("!")
        lines.append("! Deliberately not emitted as host rules:")
        for host, reason in sorted(SKIP.items()):
            lines.append(f"!   {host} - {reason}")

    ordered = [c for c in CATEGORY_ORDER if c in by_category]
    ordered += sorted(c for c in by_category if c not in CATEGORY_ORDER)
    for category in ordered:
        lines.append("")
        lines.append(f"! {CATEGORY_TITLE.get(category, category)}")
        for host in sorted(set(by_category[category])):
            lines.append(f"||{host}^$important")
    return "\n".join(lines) + "\n"


def split(text):
    start = text.find(START)
    if start == -1:
        return text, None
    end = text.find(END, start)
    if end == -1:
        raise SystemExit("superadblock: start marker without end marker")
    end = text.find("\n", end)
    return text[:start], text[end + 1:]


def main(argv):
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    with open(LIST, encoding="utf-8") as f:
        current = f.read()

    head, _tail = split(current)
    desired = head.rstrip("\n") + "\n\n" + render_section(None, head)

    if args.check:
        if current != desired:
            print("superadblock: astra-telemetry.txt strict section is stale", file=sys.stderr)
            print("superadblock: run blocker/tools/superadblock.py --write", file=sys.stderr)
            return 1
        print("superadblock: strict host section current")
        return 0

    with open(LIST, "w", encoding="utf-8") as f:
        f.write(desired)
    emitted = sum(
        1
        for line in desired.splitlines()
        if line.startswith("||") and line.endswith("$important")
    )
    print(f"superadblock: wrote strict section ({emitted} host rules)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
