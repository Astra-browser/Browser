def PATH(spec):
    return os.path.join(ROOT, spec["inventory"])


def load(spec):
    with open(PATH(spec), encoding="utf-8") as f:
        return json.load(f)


def categories_of(entry):
    categories = entry.get("categories") or [entry.get("category")]
    return [category for category in categories if category]


def host_covered(host, rules):
    """True when a host rule for this host or a parent already covers it."""
    if f"||{host}^$important" in rules:
        return True
    parent = host
    while "." in parent:
        parent = parent[parent.index(".") + 1 :]
        if f"||{parent}^$important" in rules:
            return True
    return False


def render_section(spec, data, rules):
    """Render one strict section; `rules` carries the rules already emitted."""
    lines = [
        spec["start"],
        "! Regenerate with: python3 blocker/tools/superadblock.py --write",
        f"! Source inventory: {spec['inventory']}",
        f"! Captured: {data['captured']} from {data['source']}",
        "!",
    ]
    lines += spec["intro"]

    skip = spec["skip"]
    if skip:
        lines.append("!")
        lines.append("! Deliberately not emitted as host rules:")
        for host, reason in sorted(skip.items()):
            lines.append(f"!   {host} - {reason}")

    by_category = {}
    skipped = 0
    for entry in data["hosts"]:
        host = entry["host"].lower()
        if host in skip:
            continue
        if host_covered(host, rules):
            skipped += 1
            continue
        rule = f"||{host}^$important"
        rules.add(rule)
        for category in categories_of(entry)[:1]:
            by_category.setdefault(category, []).append(host)

    ordered = [c for c in spec["orders"] if c in by_category]
    ordered += sorted(c for c in by_category if c not in spec["orders"])
    for category in ordered:
        lines.append("")
        lines.append(f"! {spec['titles'].get(category, category)}")
        for host in sorted(set(by_category[category])):
            lines.append(f"||{host}^$important")
    lines.append(spec["end"])
    return "\n".join(lines) + "\n", skipped


def split(text):
    """Return (head, tail): head is before the first section, tail after the last."""
    first = None
    last_end = None
    for spec in SECTIONS:
        index = text.find(spec["start"])
        if index == -1:
            continue
        if first is None or index < first:
            first = index
        end = text.find(spec["end"], index)
        if end == -1:
            raise SystemExit(
                f"superadblock: {spec['name']} start marker without end marker"
            )
        end = text.find("\n", end)
        if end == -1:
            end = len(text)
        if last_end is None or end > last_end:
            last_end = end
    if first is None:
        return text, ""
    return text[:first], text[last_end:] if last_end is not None else ""


def build(text):
    head, tail = split(text)
    rules = {
        line.strip()
        for line in head.splitlines()
        if line.strip() and not line.strip().startswith("!")
    }
    body = head.rstrip("\n") + "\n\n"
    counts = {}
    for spec in SECTIONS:
        section, skipped = render_section(spec, load(spec), rules)
        body += section + "\n"
        counts[spec["name"]] = (len(section.splitlines()), skipped)
    if tail.strip():
        # Hand-maintained rules after the last generated section are preserved.
        body += tail.rstrip("\n") + "\n"
    return body, rules, counts


def main(argv):
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    with open(LIST, encoding="utf-8") as f:
        current = f.read()

    desired, rules, counts = build(current)

    if args.check:
        if current != desired:
            print(
                "superadblock: astra-telemetry.txt strict sections are stale",
                file=sys.stderr,
            )
            print(
                "superadblock: run blocker/tools/superadblock.py --write",
                file=sys.stderr,
            )
            return 1
        print(f"superadblock: strict host sections current ({len(rules)} rules)")
        return 0

    with open(LIST, "w", encoding="utf-8") as f:
        f.write(desired)
    emitted = sum(
        1
        for line in desired.splitlines()
        if line.startswith("||") and line.endswith("$important")
    )
    for name, (_, skipped) in counts.items():
        print(f"superadblock: {name} section covered by earlier rules: {skipped}")
    print(f"superadblock: wrote strict sections ({emitted} host rules)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
