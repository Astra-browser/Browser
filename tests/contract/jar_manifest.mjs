// The host half of `overlay/astra/jar.mn` is generated from the filesystem.
//
// What this catches: a new `overlay/astra/host/*.sys.mjs` or
// `overlay/astra/host/schemas/*.json` that never reaches the packaged
// manifest. The failure is silent at runtime: Node contract tests import the
// file from disk, and `ui/shell/src/host.js` caches a failed import as null,
// so the surface goes disabled instead of erroring. `wire_coverage.mjs` only
// checks modules another host module imports; this suite checks every file the
// host owns.
//
// The lines live between the BEGIN/END HOST API markers, sorted, and the only
// documented exclusion is `BootSidecar.sys.mjs` (HOST_API_v1.md §Modules: a
// compatibility re-export, not packaged).
//
// Usage: node tests/contract/jar_manifest.mjs
// Exit 0 on PASS, 1 on FAIL. Stdlib only.
import { readFile, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.dirname(path.dirname(path.dirname(fileURLToPath(import.meta.url))));
const HOST = path.join(ROOT, "overlay", "astra", "host");
const JAR = path.join(ROOT, "overlay", "astra", "jar.mn");

const BEGIN =
  "  # BEGIN HOST API (generated by `node tools/stage-host-jar.mjs`; do not hand-edit; BootSidecar.sys.mjs is not packaged)";
const END = "  # END HOST API";

// Named, not inferred: the one host module the manifest must not carry.
const EXCLUDED = new Map([
  ["BootSidecar.sys.mjs", "compatibility re-export; HOST_API_v1.md §Modules"],
]);

let passed = 0;
let failed = 0;
function check(name, cond, detail) {
  if (cond) {
    passed += 1;
    console.log(`PASS ${name}`);
  } else {
    failed += 1;
    console.error(`FAIL ${name}`);
    if (detail) console.error(`  ${detail}`);
  }
}

const source = await readFile(JAR, "utf8");
const lines = source.split("\n");

const moduleLine =
  /^\s*content\/astra\/res\/host\/([^/\s]+\.sys\.mjs)\s+\(host\/([^)\s]+\.sys\.mjs)\)\s*$/u;
const schemaLine =
  /^\s*content\/astra\/res\/host\/schemas\/([^/\s]+\.json)\s+\(host\/schemas\/([^)\s]+\.json)\)\s*$/u;

const listedModules = new Map();
const listedSchemas = new Map();
const hostLineIndices = [];
const mismatched = [];
for (const [index, line] of lines.entries()) {
  const moduleMatch = moduleLine.exec(line);
  const schemaMatch = moduleMatch ? null : schemaLine.exec(line);
  if (!moduleMatch && !schemaMatch) continue;
  hostLineIndices.push(index);
  const match = moduleMatch ?? schemaMatch;
  if (match[1] !== match[2]) mismatched.push(`line ${index + 1}: ${match[1]} -> ${match[2]}`);
  const target = moduleMatch ? listedModules : listedSchemas;
  target.set(match[1], (target.get(match[1]) ?? 0) + 1);
}

const diskModules = (await readdir(HOST, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith(".sys.mjs"))
  .map((entry) => entry.name)
  .filter((name) => !EXCLUDED.has(name))
  .sort();
const diskSchemas = (await readdir(path.join(HOST, "schemas"), { withFileTypes: true }))
  .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
  .map((entry) => entry.name)
  .sort();

const missingModules = diskModules.filter((name) => !listedModules.has(name));
const extraModules = [...listedModules.keys()].filter((name) => !diskModules.includes(name));
const missingSchemas = diskSchemas.filter((name) => !listedSchemas.has(name));
const extraSchemas = [...listedSchemas.keys()].filter((name) => !diskSchemas.includes(name));

check(
  `every host module on disk is packaged (${diskModules.length} files)`,
  missingModules.length === 0,
  missingModules.map((name) => `missing host/${name}`).join("\n  "),
);
check(
  `jar.mn lists no host module that is not on disk (${listedModules.size} lines)`,
  extraModules.length === 0,
  extraModules.map((name) => `extra host/${name}`).join("\n  "),
);
check(
  `every schema on disk is packaged (${diskSchemas.length} files)`,
  missingSchemas.length === 0,
  missingSchemas.map((name) => `missing host/schemas/${name}`).join("\n  "),
);
check(
  `jar.mn lists no schema that is not on disk (${listedSchemas.size} lines)`,
  extraSchemas.length === 0,
  extraSchemas.map((name) => `extra host/schemas/${name}`).join("\n  "),
);
check(
  "each host file is listed exactly once",
  [...listedModules.values(), ...listedSchemas.values()].every((count) => count === 1),
  [...listedModules, ...listedSchemas]
    .filter(([, count]) => count !== 1)
    .map(([name, count]) => `${name} listed ${count} times`)
    .join("\n  "),
);
check(
  "the documented BootSidecar.sys.mjs exclusion is not packaged",
  !listedModules.has("BootSidecar.sys.mjs"),
  EXCLUDED.get("BootSidecar.sys.mjs"),
);
check(
  "every host line maps to its own file",
  mismatched.length === 0,
  mismatched.join("\n  "),
);

// The generated block is the provenance guard: the list is not hand-written.
const start = lines.indexOf(BEGIN);
const end = lines.indexOf(END);
check("jar.mn has a HOST API block", start !== -1 && end > start);
const inBlock = (index) => start !== -1 && end > start && index > start && index < end;
const outside = hostLineIndices.filter((index) => !inBlock(index));
check(
  "no host line lives outside the generated block",
  start !== -1 && end > start && outside.length === 0,
  outside.map((index) => `line ${index + 1}`).join(", "),
);

if (start !== -1 && end > start) {
  const blockModules = [];
  const blockSchemas = [];
  for (const line of lines.slice(start + 1, end)) {
    const moduleMatch = moduleLine.exec(line);
    if (moduleMatch) {
      blockModules.push(moduleMatch[1]);
      continue;
    }
    const schemaMatch = schemaLine.exec(line);
    if (schemaMatch) blockSchemas.push(schemaMatch[1]);
  }
  check(
    "the block lists host modules in sorted order",
    JSON.stringify(blockModules) === JSON.stringify([...blockModules].sort()),
    blockModules.join(" "),
  );
  check(
    "the block lists schemas in sorted order",
    JSON.stringify(blockSchemas) === JSON.stringify([...blockSchemas].sort()),
    blockSchemas.join(" "),
  );
  let sawSchema = false;
  let interleaved = false;
  for (const index of hostLineIndices) {
    if (lines[index].includes(".json")) sawSchema = true;
    else if (sawSchema) interleaved = true;
  }
  check("the block lists every module before every schema", !interleaved);
}

console.log(`\njar manifest: ${failed === 0 ? "PASS" : "FAIL"} (${passed} checks, ${failed} failed)`);
process.exit(failed === 0 ? 0 : 1);
