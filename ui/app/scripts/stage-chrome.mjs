// P3-T15: stage the chrome app build into the overlay + audit it.
//
// `vite build --config vite.chrome.ts` already emits directly into
// `overlay/astra/chrome/app/` (outDir, wiped first). This script then:
//   1. restores static (non-bundled) chrome/app files that live in the ui
//      tree (none today: P3-T21 removed the relay framescript when the app
//      became a first-party chrome document),
//   2. regenerates the `# BEGIN/END CHROME APP` block in `overlay/astra/jar.mn`
//      (sorted file list — deterministic; the shell loader resolves the app
//      page through the `resource://astra-app/` mapping, so no hashed name
//      is ever hardcoded), and
//   3. audits chrome-CSP safety (U-04): every staged .html must have no inline
//      <script> (src-less), no remote (http(s):) script/link URLs, and only
//      relative asset references.
//
// Usage: `bun run --filter @astra/frame build:chrome` (builds, then runs this).
// Stdlib only.

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = new URL(".", import.meta.url);
const appDir = fileURLToPath(new URL("../../../overlay/astra/chrome/app", appRoot));
const jarMn = fileURLToPath(new URL("../../../overlay/astra/jar.mn", appRoot));

const BEGIN = "  # BEGIN CHROME APP (P3-T15, generated by `bun run --filter @astra/frame build:chrome`; do not hand-edit)";
const END = "  # END CHROME APP (P3-T15)";

async function listFiles(dir, base = "") {
  const out = [];
  for (const entry of await readdir(join(dir, base), { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...(await listFiles(dir, rel)));
    else if (entry.isFile()) out.push(rel);
  }
  return out.sort();
}

const files = await listFiles(appDir);
if (!files.includes("browser-chrome.html")) {
  throw new Error(`stage-chrome: ${appDir} has no browser-chrome.html (run the chrome build first)`);
}

// --- static files (not bundled; restored after emptyOutDir wipes them) ---
// None: the app ships only its bundled document + assets (P3-T21).
files.sort();

// --- CSP audit (U-04) ---
const failures = [];
for (const rel of files.filter((f) => f.endsWith(".html"))) {
  const text = await readFile(join(appDir, rel), "utf8");
  const scripts = [...text.matchAll(/<script\b([^>]*)>/gi)].map((m) => m[1]);
  for (const attrs of scripts) {
    if (!/\bsrc\s*=/i.test(attrs)) failures.push(`${rel}: inline <script> without src`);
    const src = attrs.match(/\bsrc\s*=\s*["']([^"']+)["']/i)?.[1] ?? "";
    if (/^https?:\/\//i.test(src)) failures.push(`${rel}: remote script ${src}`);
    if (src.startsWith("/")) failures.push(`${rel}: absolute script URL ${src}`);
  }
  for (const m of text.matchAll(/<(?:link|img|source)\b[^>]*\b(?:href|src)\s*=\s*["']([^"']+)["']/gi)) {
    const url = m[1];
    if (/^https?:\/\//i.test(url)) failures.push(`${rel}: remote subresource ${url}`);
    if (url.startsWith("/") && !url.startsWith("//")) failures.push(`${rel}: absolute subresource URL ${url}`);
  }
}
if (failures.length) {
  throw new Error(`stage-chrome: CSP audit failed:\n  - ${failures.join("\n  - ")}`);
}

// --- jar.mn regeneration ---
const lines = files.map((f) => `  content/astra/app/${f} (chrome/app/${f})`);
const jar = await readFile(jarMn, "utf8");
const start = jar.indexOf(BEGIN);
const end = jar.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  throw new Error("stage-chrome: jar.mn CHROME APP markers missing");
}
const before = jar.slice(0, start);
const after = jar.slice(end + END.length);
const block = [BEGIN, ...lines, END].join("\n");
await writeFile(jarMn, `${before}${block}${after}`);

// Brand note: the bundle carries the Appendix C prev:-channel rename map
// (EVENT_RENAMES), which names the previous product; tools/brand-lint.sh
// excludes this generated dir like other build outputs (see SHELL_APP.md).
console.warn(`stage-chrome: staged ${files.length} files, jar.mn block rewritten, CSP audit clean`);
