// P3-T15 chrome build (additive; app sources untouched): the production
// browser graph packaged for `chrome://astra/app/`. Reuses frameConfig so
// code-splitting, i18n, Tailwind and the Svelte setup stay identical to the
// golden build, then overrides only what chrome packaging needs:
//   - input: browser-chrome.html (HOST-mode entry, chrome-entry/) instead of
//     the Tauri browser.html. panel/onboarding are separate surfaces.
//   - base "./": absolute `/assets/...` URLs would resolve against the
//     chrome scheme root; relative URLs resolve against the page URL, so the
//     same bundle also keeps working from any mount point.
//   - outDir overlay/astra/chrome/app: the overlay is the packaging unit
//     (P1-T05); `forge overlay` copies the tree, jar.mn registers each file
//     (regenerated by scripts/stage-chrome.mjs — no hardcoded hashes).
//   - `@tauri-apps/api/{core,event,window}` aliased to the `@astra/bridge`
//     Tauri shim: there is no Tauri runtime in Firefox; the shim routes
//     invoke/listen through the bridge (HOST dispatch in chrome, MOCK in
//     standalone). Bare `@tauri-apps/api` is never imported (checked: only
//     the three subpaths appear in src), so three aliases cover the graph.
// CSP: no config change needed — frameConfig already sets modulePreload
// false and emits no inline scripts (U-04); stage-chrome.mjs audits that.
import { fileURLToPath } from "node:url";
import { defineConfig } from "vite";
import { alias } from "./aliases.ts";
import { frameConfig } from "./vite.frame.ts";

// The bridge ships source (exports -> src/index.ts, no dist build), so the
// shim alias points at source like every other alias in this repo.
const shim = fileURLToPath(new URL("../packages/bridge/src/tauri-shim.ts", import.meta.url));

const base = frameConfig(["browser"]);
const baseBuild = base.build ?? {};
const baseRolldown = baseBuild.rolldownOptions ?? {};
const baseOutput = baseRolldown.output ?? {};
const basePlugins = base.plugins ?? [];

// Drop astra-bootstrap-boundaries: it pins the golden page set (entry facade
// must end in /browser.html, byte budgets recorded for the golden graph).
// The chrome build is the same module graph through a different entry, so
// the golden `build`/`budgets` gates stay authoritative; stage-chrome.mjs
// owns the chrome-specific audits (CSP, jar.mn) instead.
const plugins = (Array.isArray(basePlugins) ? basePlugins.flat(10) : [basePlugins]).filter(
  (p) => p && (p as { name?: string }).name !== "astra-bootstrap-boundaries",
);

export default defineConfig({
  ...base,
  base: "./",
  plugins,
  resolve: {
    ...base.resolve,
    alias: {
      ...alias,
      "@tauri-apps/api/core": shim,
      "@tauri-apps/api/event": shim,
      "@tauri-apps/api/window": shim,
    },
  },
  build: {
    ...baseBuild,
    outDir: fileURLToPath(new URL("../../overlay/astra/chrome/app", import.meta.url)),
    emptyOutDir: true,
    rolldownOptions: {
      ...baseRolldown,
      output: {
        ...baseOutput,
        // jar.mn entries allow [\w\d.\-_/+@] only; Vite joins merged chunk
        // names with `~` (e.g. messages~AboutPage-HASH.js), which breaks
        // `mach build faster` at jar parsing. Dashes keep names readable.
        // (Replicates the default sanitizer's null-byte handling, which a
        // custom function replaces.)
        sanitizeFileName: (name: string) =>
          // eslint-disable-next-line no-control-regex -- a filename can carry a control byte; Vite's default sanitizer strips it.
          name.replace(/[?*~|<>:"\\\x00-\x1f]/g, (ch) => (ch === "~" ? "-" : "_")),
      },
      input: {
        "browser-chrome": fileURLToPath(new URL("./browser-chrome.html", import.meta.url)),
      },
    },
  },
});
